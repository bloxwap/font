"""Kana skeletons in the 1000 x 1000 design grid (y up).

Rounded modern gothic: monoline strokes, round caps; corners are separate
strokes meeting on one skeleton point (round caps make the soft corner);
loops are single smooth strokes that cross themselves.  `k.t` is the
stroke thickness in design units (weight dependent): loops and counters
grow with it linearly so they stay open at Black.

Each shape is f(k) with k a ctx.K.  HIRA / KATA map romanised names to
shapes.
"""
from __future__ import annotations

HIRA = {}
KATA = {}


def hira(name):
    def deco(f):
        HIRA[name] = f
        return f
    return deco


def kata(name):
    def deco(f):
        KATA[name] = f
        return f
    return deco


# ---------------------------------------------------------------------------
# shared parts
# ---------------------------------------------------------------------------

def hook_stem(k, x, top, bot):
    """Left stroke of け に は ほ: a long gently bowed vertical ending in a
    small kick to the upper right."""
    k.S((x, top, -90), (x + 18, bot + 90, -84), (x + 70, bot + 40, -10, 0.5), (x + 125, bot + 115, 55))


def loop_tail(k, x, top, bot, lw=None, tail=330, lh=None, tail_y=None):
    """Stem coming down at x, looping clockwise at the bottom left and
    leaving to the lower right (は ほ ま よ な)."""
    t = k.t
    lw = (230 + 0.55 * t) if lw is None else lw
    lh = (230 + 0.75 * t) if lh is None else lh
    ty = bot + 40 if tail_y is None else tail_y
    k.S((x, top, -90),
        (x, bot + 0.62 * lh, -90),
        (x - 0.42 * lw, bot, 180, 0.6),
        (x - lw, bot + 0.46 * lh, 90, 0.6),
        (x - 0.45 * lw, bot + lh, -5, 0.6),
        (x + 0.30 * tail, bot + 0.55 * lh, -50),
        (x + tail, ty, -25))


def zig(k, x0, y0, x1, y1, x2, y2):
    """Two corner strokes: x0,y0 -> x1,y1 -> x2,y2."""
    k.L(x0, y0, x1, y1)
    k.L(x1, y1, x2, y2, 0.96)




def end_loop(k, xr, yr):
    """ぬ ね: the stroke comes down the right side at xr, curls clockwise
    into a loop at the bottom right and leaves to the lower right."""
    sz = 185 + 0.6 * k.t
    cx = xr - 0.5 * sz
    return [(xr, yr, -90), (cx, 40, 180, 0.6), (cx - 0.5 * sz, 40 + 0.5 * sz, 90, 0.6),
            (cx + 0.02 * sz, 40 + sz, -8, 0.6), (xr + 25, 25, -62)]


def side_loop(k, x, yc, sz):
    """D-shaped loop hanging on the left of a stem at x (す む)."""
    k.S((x, yc + 0.42 * sz, -125), (x - 0.62 * sz, yc + 0.05 * sz, -90, 0.6),
        (x - 0.25 * sz, yc - 0.5 * sz, 0, 0.6), (x, yc - 0.3 * sz, 70))


