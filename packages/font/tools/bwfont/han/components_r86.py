# hook helpers (short, rounded) ----------------------------------------------
def _vhook(x, y0, y1=1000, d=130):
    """竖钩: vertical from (x, y0) to y1, short hook to the left."""
    return f"M{x} {y0} L{x} {y1 - 90} Q{x} {y1} {x - d} {y1 - 40}"


def _hzhook(x0, y0, x1, y1=1000, d=120):
    """横折钩: horizontal to x1, down to y1, short hook to the left."""
    return f"M{x0} {y0} L{x1} {y0} L{x1} {y1 - 90} Q{x1} {y1} {x1 - d} {y1 - 40}"


def _wanhook(x, y0, x1, y1=980, top=820):
    """竖弯钩: vertical, round corner, run to the right, hook up."""
    return f"M{x} {y0} L{x} {y1 - 120} Q{x} {y1} {x + 120} {y1} L{x1 - 60} {y1} Q{x1} {y1} {x1} {top}"


def _box(x0, y0, x1, y1):
    """口 as three strokes: 丨, 横折, 横."""
    return (f"M{x0} {y0} L{x0} {y1}", f"M{x0} {y0} L{x1} {y0} L{x1} {y1}",
            f"M{x0} {y1} L{x1} {y1}")


