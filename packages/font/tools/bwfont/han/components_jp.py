def _vhook(x, y0, y1=1000, d=130):
    """竖钩: vertical from (x, y0) to y1, short hook to the left."""
    return f"M{x} {y0} L{x} {y1 - 90} Q{x} {y1} {x - d} {y1 - 40}"


def _hzg(x0, y, x1, y1=1000, d=120):
    """横折钩: horizontal at y from x0 to x1, down to y1, short hook left."""
    return f"M{x0} {y} L{x1} {y} L{x1} {y1 - 90} Q{x1} {y1} {x1 - d} {y1 - 40}"


def _wanhook(x, y0, x1, y1=980, top=820):
    """竖弯钩: vertical, round corner, run to the right, hook up."""
    return f"M{x} {y0} L{x} {y1 - 120} Q{x} {y1} {x + 120} {y1} L{x1 - 60} {y1} Q{x1} {y1} {x1} {top}"


def _box(x0, y0, x1, y1):
    """口 as three strokes: 丨, 横折, 横."""
    return (f"M{x0} {y0} L{x0} {y1}", f"M{x0} {y0} L{x1} {y0} L{x1} {y1}",
            f"M{x0} {y1} L{x1} {y1}")


def _rows(x0, y0, x1, y1, n):
    """A box with n rows (日 n=2, 目 n=3): 丨, 横折, (n-1) inner 横, bottom 横."""
    out = [f"M{x0} {y0} L{x0} {y1}", f"M{x0} {y0} L{x1} {y0} L{x1} {y1}"]
    for i in range(1, n):
        y = round(y0 + (y1 - y0) * i / n)
        out.append(f"M{x0} {y} L{x1} {y}")
    out.append(f"M{x0} {y1} L{x1} {y1}")
    return out


def _dots4(x0, x1, y0, y1):
    """灬: four short dots between x0..x1, from y0 down to y1 (keep y1 - y0 ≈ 100
    so narrow slots don't read them as vertical strokes)."""
    w = (x1 - x0) / 3
    xs = [x0 + w * i for i in range(4)]
    return (f"M{xs[0] + 50:.0f} {y0} L{xs[0] - 30:.0f} {y1}",
            f"M{xs[1] - 10:.0f} {y0} L{xs[1] + 40:.0f} {y1}",
            f"M{xs[2] - 10:.0f} {y0} L{xs[2] + 50:.0f} {y1}",
            f"M{xs[3] - 60:.0f} {y0 - 10} L{xs[3] + 40:.0f} {y1 - 20}")


