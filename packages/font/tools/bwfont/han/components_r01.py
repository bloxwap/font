def vhook(x, y0, y1=1000, dx=-150):
    """竖钩: vertical at x from y0 to y1 with a short left hook."""
    return f"M{x} {y0} L{x} {y1 - 90} Q{x} {y1} {x + dx} {y1 - 50}"


def hzg(x0, y, x1, y1=1000, dx=-130):
    """横折钩: horizontal at y from x0 to x1, down to y1, short hook left."""
    return f"M{x0} {y} L{x1} {y} L{x1} {y1 - 90} Q{x1} {y1} {x1 + dx} {y1 - 40}"


def swg(x, y0, x1=1000, y1=1000, hook=170):
    """竖弯钩: vertical at x from y0 curving into a bottom horizontal to x1, hook up."""
    return f"M{x} {y0} L{x} {y1 - 130} Q{x} {y1} {x + 130} {y1} L{x1} {y1} L{x1} {y1 - hook}"


