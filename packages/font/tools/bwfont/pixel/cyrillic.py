# letters with a descender tick: cp -> (source glyph, column of the tick)
DESCENDERS = {
    0x496: ("uni0416", 4), 0x497: ("uni0436", 4),     # Җ җ
    0x498: ("uni0417", 2), 0x499: ("uni0437", 2),     # Ҙ ҙ
    0x49A: ("K", 4), 0x49B: (None, 4),                # Қ қ
    0x4A2: ("H", 4), 0x4A3: ("uni043D", 4),           # Ң ң
    0x4B2: ("X", 4), 0x4B3: ("x", 4),                 # Ҳ ҳ
    0x4B6: ("uni0427", 4), 0x4B7: ("uni0447", 4),     # Ҷ ҷ
    0x4AA: ("C", 2), 0x4AB: ("c", 2),                 # Ҫ ҫ
    0x4AC: ("T", 2), 0x4AD: ("uni0442", 2),           # Ҭ ҭ
    0x4C5: ("uni041B", 4), 0x4C6: ("uni043B", 4),     # Ӆ ӆ
    0x4C9: ("uni0418", 4), 0x4CA: ("uni0438", 4),     # Ӊ ӊ
    0x4CD: ("M", 4), 0x4CE: ("uni043C", 4),           # Ӎ ӎ
    0x4CB: ("uni0427", 0), 0x4CC: ("uni0447", 0),     # Ӌ ӌ
    0x4BC: (None, 0),
}


def register():
    parse(UPPER)
    parse(LOWER)
    # қ: к with the leg kicked out
    kk = pix_of("uni043A") - {(400, 0)} | {(400, 0), (500, 0), (500, -1)}
    derive_cp(0x49B, kk)
    for cp, (src, col) in DESCENDERS.items():
        if src is None:
            continue
        derive_cp(cp, pix_of(src) | {(100 + 100 * col, -1)})
    derive_cp(0x45B, pix_of("hbar"))                   # ћ
    derive_cp(0x4E0, pix_of(char_name("Ʒ")))           # Ӡ
    derive_cp(0x4E1, pix_of(char_name("ʒ")))           # ӡ
    derive_cp(0x472, pix_of("Theta"))                  # Ѳ
    derive_cp(0x473, pix_of("obarred"))                # ѳ
    alias(0x4D4, "AE")                                 # Ӕ
    alias(0x4D5, "ae")                                 # ӕ
