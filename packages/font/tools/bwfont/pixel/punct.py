def register():
    parse(ASCII1)
    parse(LATIN1)
    parse(GENERAL)
    parse(EXTRA)
    parse(ORDS)
    parse(RINGS)
    parse(TINY)
    # superiors / inferiors / numerators / denominators
    for i, d in enumerate(DIGITS):
        _tiny(d, 2, [SUPS_CP[i]], name_for(SUPS_CP[i]))
        _tiny(d, -2, [SUBS_CP[i]], name_for(SUBS_CP[i]))
        add(PixelDef(d + ".sups", [], set(), comps=[(name_for(SUPS_CP[i]), 0, 0)]))
        add(PixelDef(d + ".numr", [], set(), comps=[(name_for(SUPS_CP[i]), 0, 0)]))
        add(PixelDef(d + ".subs", [], set(), comps=[(name_for(SUBS_CP[i]), 0, 0)]))
        _tiny(d, 0, [], d + ".dnom")
    for base, sup, sub in (("plus", 0x207A, 0x208A), ("minus", 0x207B, 0x208B), ("equal", 0x207C, 0x208C),
                           ("parenleft", 0x207D, 0x208D), ("parenright", 0x207E, 0x208E)):
        _tiny(base, 2, [sup], name_for(sup))
        _tiny(base, -2, [sub], name_for(sub))
    for n in [n for n in art.REG if n.endswith(".t")]:
        del art.REG[n]
        art.ORDER.remove(n)
    derive("fraction", [0x2044], art.REG["slash"].pix)
    derive("minus", [0x2212], {(x, 3) for x in range(100, 600, 100)})
    derive("periodcentered", [0xB7], {(300, 3)})
    alias(0x2011, "hyphen")
    alias(0xAD, "hyphen")
    alias(0x2010, "hyphen")

    # spaces (all one cell wide; zero-width ones have no advance)
    add(PixelDef("space", [0x20], set()))
    add(PixelDef("uni00A0", [0xA0], set()))
    for cp in list(range(0x2000, 0x200B)) + [0x202F, 0x205F]:
        add(PixelDef(name_for(cp), [cp], set()))
    for cp in (0x200B, 0x200C, 0x200D, 0x2060, 0xFEFF):
        add(PixelDef(name_for(cp), [cp], set(), advance=0))
    # .notdef: a hollow box
    nd = {(x, r) for x in (100, 500) for r in range(0, 7)} | {(x, r) for x in (200, 300, 400) for r in (0, 6)}
    add(PixelDef(".notdef", [], nd))
    art.ORDER.remove(".notdef")
    art.ORDER.insert(0, ".notdef")
