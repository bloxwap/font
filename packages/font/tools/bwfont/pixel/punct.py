DIGITS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
SUPS_CP = [0x2070, 0xB9, 0xB2, 0xB3, 0x2074, 0x2075, 0x2076, 0x2077, 0x2078, 0x2079]
SUBS_CP = list(range(0x2080, 0x208A))


def _tiny(name, dy, cps=(), label=None):
    src = art.REG[name + ".t"].pix
    return derive(label, list(cps), {(x, r + dy) for x, r in src})


