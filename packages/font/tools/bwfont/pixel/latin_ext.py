def register():
    parse(EXT_UC)
    parse(EXT_LC)
    parse(FIXES)
    alias(0x110, char_name("Ð"))          # Đ looks like Ð
    alias(0x189, char_name("Ð"))          # Ɖ (African D)
    derive_cp(0x241, pix_of(char_name("ʔ")))
    derive_cp(0x261, pix_of("g"))          # ɡ script g
    derive_cp(0x1DD, pix_of("schwa"))      # ǝ turned e
    derive_cp(0x1A7, mirror(pix_of("S")))  # Ƨ
    derive_cp(0x1B8, mirror(pix_of(char_name("Ʒ"))))  # Ƹ
    derive_cp(0x1B9, mirror(pix_of(char_name("ʒ"))))  # ƹ
    # turned / reversed letters from existing bitmaps
    rot_lc = {0x250: "a", 0x265: "h", 0x26F: "m", 0x279: "r", 0x287: "t", 0x28C: "v", 0x28D: "w",
              0x28E: "y", 0x29E: "k", 0x25F: "f", 0x252: char_name("ɑ")}
    for cp, src in rot_lc.items():
        derive_cp(cp, rot180(pix_of(src), 4))
    derive_cp(0x245, rot180(pix_of("V"), 6))           # Ʌ
    derive_cp(0x258, mirror(pix_of("e")))              # ɘ
    derive_cp(0x25C, mirror(pix_of(char_name("ɛ"))))   # ɜ
    derive_cp(0x1A8, mirror(pix_of("s")))              # ƨ
    derive_cp(0x21D, {(x, r - 2) for x, r in pix_of(char_name("Ȝ"))})       # ȝ
    derive_cp(0x223, {(x, r) for x, r in pix_of(char_name("Ȣ")) if r <= 4})  # ȣ
    derive_cp(0x2C66, pix_of("t") | {(500, 6)})       # ⱦ
    derive_cp(0x23C, pix_of("c") | {(500, 5), (100, -1)})   # ȼ
    derive_cp(0x247, pix_of("e") | {(500, 5), (100, -1)})   # ɇ
    derive_cp(0x24F, pix_of("y") | {(200, 2), (300, 2), (400, 2)})  # ɏ
    derive_cp(0xA78C, {(300, 4), (300, 3)})            # ꞌ saltillo
