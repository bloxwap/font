def _has(cp):
    return name_for(cp) in art.REG


def _d(cp, pix, **kw):
    if _has(cp):
        return
    art.derive_cp(cp, pix, **kw)


def _a(cp, src, dx=0, dy=0):
    if _has(cp) or src not in art.REG:
        return
    art.alias(cp, src, dx, dy)


def P(ch):
    return pix_of(char_name(ch)) if len(ch) == 1 else pix_of(ch)


def desc(pix, col, rows=(-1,)):
    return set(pix) | {(100 + 100 * col, r) for r in rows}


def register():
    for b in (GEOMETRIC, MATH, ARROWS, MISC, LETTERLIKE, LETTERS, PUNCT):
        parse(b, skip_existing=True)
    parse(TINY)
    parse(TINY2)
    for n in ("∆.x", "⇤.x"):
        if n in art.REG:
            del art.REG[n]
            art.ORDER.remove(n)
    # tiny letters
    for k, cp in TINY_MAP_SUP.items():
        _d(cp, {(x, r + 3) for x, r in art.REG[k + ".t"].pix})
    for k, cp in TINY_MAP_SUB.items():
        _d(cp, {(x, r - 2) for x, r in art.REG[k + ".t"].pix})
    for k, cp in MOD_SMALL.items():
        if k + ".t" in art.REG:
            _d(cp, {(x, r + 3) for x, r in art.REG[k + ".t"].pix})
    for n in [n for n in art.REG if n.endswith(".t")]:
        del art.REG[n]
        art.ORDER.remove(n)
    for cp, src in SMALL_CAPS.items():
        if src in art.REG and art.REG[src].pix:
            _d(cp, smallcap(art.REG[src].pix))
    _d(0x1D0D, P("uni043C"))                                   # ᴍ
    _d(0x1D20, P("v"))                                         # ᴠ
    _d(0x1D1A, rot180(smallcap(P("R")), 4))                    # ᴚ
